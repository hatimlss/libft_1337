#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int			i;
	int			s;
	long		t;
	const char	*p1;

	i = 0;
	s = 1;
	t = 0;
	p1 = nptr;
	while (p1[i] == 32 || (p1[i] >= 9 && p1[i] <= 13))
		i++;
	if (p1[i] == '+' || p1[i] == '-')
	{
		if (p1[i] == '-')
			s = -1;
		i++;
	}
	while (p1[i] >= '0' && p1[i] <= '9')
	{
		t = t * 10 + (p1[i] - '0');
		i++;
	}
	return ((t * s));
}
